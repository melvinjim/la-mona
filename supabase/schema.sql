-- 1. Contenido del sitio -----------------------------------------------------
-- Dos filas: 'menu' (el menú completo) y 'site' (datos del restaurante y la promoción).
-- Se guardan como JSON con la misma forma de src/lib/types.ts.

create table if not exists public.content (
  key         text primary key,
  data        jsonb not null,
  updated_at  timestamptz not null default now(),
  constraint content_key_valido check (key in ('menu', 'site'))
);

alter table public.content enable row level security;

-- Cualquiera puede leer el menú: es lo que muestra la página pública.
drop policy if exists "content: lectura pública" on public.content;
create policy "content: lectura pública"
  on public.content for select
  to anon, authenticated
  using (true);

-- Solo quien haya iniciado sesión puede modificarlo (el panel administrativo).
drop policy if exists "content: escritura del administrador" on public.content;
create policy "content: escritura del administrador"
  on public.content for all
  to authenticated
  using (true)
  with check (true);

-- 2. Barrios de domicilio ----------------------------------------------------
-- Cada barrio con su valor fijo de domicilio. Se editan en el panel (pestaña Domicilios);
-- también se pueden cargar aquí: Table Editor -> delivery_zones -> Insert -> Import data from CSV.

create table if not exists public.delivery_zones (
  id          bigint generated by default as identity primary key,
  name        text not null check (btrim(name) <> ''),
  fee         integer not null check (fee >= 0),
  name_key    text generated always as (lower(btrim(name))) stored unique,
  created_at  timestamptz not null default now()
);

alter table public.delivery_zones enable row level security;

drop policy if exists "delivery_zones: lectura pública" on public.delivery_zones;
create policy "delivery_zones: lectura pública"
  on public.delivery_zones for select
  to anon, authenticated
  using (true);

drop policy if exists "delivery_zones: escritura del administrador" on public.delivery_zones;
create policy "delivery_zones: escritura del administrador"
  on public.delivery_zones for all
  to authenticated
  using (true)
  with check (true);

grant select on public.delivery_zones to anon, authenticated;
grant insert, update, delete on public.delivery_zones to authenticated;

-- Cuándo se tocó cada barrio por última vez (columna "Última actualización" del panel).
alter table public.delivery_zones
  add column if not exists updated_at timestamptz not null default now();

create or replace function public.touch_delivery_zone()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists delivery_zones_touch on public.delivery_zones;
create trigger delivery_zones_touch
  before update on public.delivery_zones
  for each row execute function public.touch_delivery_zone();

-- Subir el domicilio de varios barrios de una sola vez.
--
-- Va como función porque desde el panel no se pueden encadenar varias sentencias en una
-- transacción: así el aumento es una sola sentencia, o entra para todos o no entra para nadie.
-- Y como suma sobre el valor que haya en ese momento, si alguien cambió una tarifa entre la
-- vista previa y la confirmación, el aumento se le aplica igual sin pisar su cambio.
create or replace function public.raise_delivery_fees(zone_ids bigint[], amount integer)
returns integer
language plpgsql
security invoker            -- respeta los permisos de quien llama: solo el administrador
as $$
declare
  changed integer;
begin
  if amount is null or amount <= 0 then
    raise exception 'El valor a sumar tiene que ser mayor que cero';
  end if;

  update public.delivery_zones
     set fee = fee + amount
   where id = any(zone_ids);

  get diagnostics changed = row_count;
  return changed;
end;
$$;

grant execute on function public.raise_delivery_fees(bigint[], integer) to authenticated;

